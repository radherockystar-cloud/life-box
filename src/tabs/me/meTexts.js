// tx('key') -> t.key ya English fallback.  tx('key', { name: 'Raj' }) -> {name} badal deta hai.
export function useMeText() {
  const { t, currentLang } = useApp();
  return (key, vars) => {
    const raw = (t && t[key]) ?? (ME_I18N[currentLang] && ME_I18N[currentLang][key]) ?? ME_DEFAULTS[key] ?? key;
    if (!vars) return raw;
    return String(raw).replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
  };
}
